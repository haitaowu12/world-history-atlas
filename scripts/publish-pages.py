#!/usr/bin/env python3
"""Publish the committed static atlas to gh-pages, without a custom Actions workflow."""
import argparse
import io
import json
from pathlib import Path, PurePosixPath
import shutil
import subprocess
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[1]
PAGES_URL = 'https://haitaowu12.github.io/world-history-atlas/'
GPT_URL = 'https://world-history-atlas-tony.techiesea.chatgpt.site/'


def git(*args, cwd=ROOT, check=True):
    return subprocess.run(['git', *args], cwd=cwd, check=check, capture_output=True)


def publish(dry_run=False):
    # Always publish a retained, committed artifact; do not silently omit local asset edits.
    if git('diff', '--quiet', 'HEAD', '--', 'dist', check=False).returncode:
        raise RuntimeError('Commit the dist/ changes before publishing.')
    if git('ls-files', '--others', '--exclude-standard', '--', 'dist').stdout.strip():
        raise RuntimeError('Commit or remove untracked dist/ files before publishing.')
    source = git('rev-parse', 'HEAD').stdout.decode().strip()
    tree = git('rev-parse', 'HEAD:dist').stdout.decode().strip()
    package = json.loads(git('show', 'HEAD:package.json').stdout)
    archive = git('archive', '--format=tar', 'HEAD:dist').stdout
    with tarfile.open(fileobj=io.BytesIO(archive)) as bundle:
        for member in bundle.getmembers():
            name = PurePosixPath(member.name)
            if name.is_absolute() or '..' in name.parts or not (member.isfile() or member.isdir()):
                raise RuntimeError('The static artifact must contain only ordinary files/directories.')
        count = sum(member.isfile() for member in bundle.getmembers())
    details = dict(app_version=package['version'], source_commit=source,
                   source_dist_tree=tree, pages_url=PAGES_URL, gpt_site_url=GPT_URL,
                   publishing_mode='branch: gh-pages / (root)')
    if dry_run:
        print(json.dumps({**details, 'static_files': count, 'dry_run': True}, indent=2))
        return
    remote = git('remote', 'get-url', 'origin').stdout.decode().strip()
    exists = git('ls-remote', '--exit-code', '--heads', 'origin', 'refs/heads/gh-pages', check=False)
    if exists.returncode not in (0, 2):
        raise RuntimeError('Could not inspect the remote gh-pages branch; nothing was published.')
    with tempfile.TemporaryDirectory(prefix='world-atlas-pages-') as directory:
        target = Path(directory)
        git('init', '--initial-branch=gh-pages', '.', cwd=target)
        git('remote', 'add', 'origin', remote, cwd=target)
        if exists.returncode == 0:
            git('fetch', '--depth=1', 'origin', 'gh-pages', cwd=target)
            git('checkout', '-B', 'gh-pages', 'FETCH_HEAD', cwd=target)
            for entry in target.iterdir():
                if entry.name == '.git':
                    continue
                if entry.is_dir() and not entry.is_symlink():
                    shutil.rmtree(entry)
                else:
                    entry.unlink()
        with tarfile.open(fileobj=io.BytesIO(archive)) as bundle:
            bundle.extractall(target, filter='data')
        # These two social metadata fields refer to this mirror, not the sibling host.
        index = target / 'index.html'
        html = index.read_text()
        for property_name, before, after in [
            ('og:url', GPT_URL, PAGES_URL),
            ('og:image', GPT_URL + 'assets/atlas-preview.jpg', PAGES_URL + 'assets/atlas-preview.jpg'),
        ]:
            original = f'<meta property="{property_name}" content="{before}">'
            if html.count(original) != 1:
                raise RuntimeError(f'Expected exactly one {property_name} field; inspect metadata before publishing.')
            html = html.replace(original, f'<meta property="{property_name}" content="{after}">')
        index.write_text(html)
        (target / '.nojekyll').touch()
        (target / 'deployment.json').write_text(json.dumps(details, indent=2) + '\n')
        (target / 'LICENSE').write_bytes(git('show', 'HEAD:LICENSE').stdout)
        (target / 'README.md').write_text(
            '# 普天之下 · World History Atlas — static publication\n\n'
            f'Published from [{source[:7]}](https://github.com/haitaowu12/world-history-atlas/commit/{source}).\n\n'
            f'[GitHub Pages]({PAGES_URL}) · [GPT Site]({GPT_URL}) · '
            '[Source and acknowledgements](https://github.com/haitaowu12/world-history-atlas).\n\n'
            'Generated by scripts/publish-pages.py from committed dist/ files. '
            'Publish edits from main; do not edit this branch by hand. '
            'Third-party assets retain the notices under data/ and assets/.\n')
        git('add', '--all', cwd=target)
        changed = git('diff', '--cached', '--quiet', cwd=target, check=False)
        if changed.returncode == 0:
            print(json.dumps({**details, 'unchanged': True}, indent=2))
            return
        if changed.returncode != 1:
            raise RuntimeError('Could not inspect the staged static publication.')
        git('commit', '-m', f'Publish atlas {package["version"]} from {source[:7]}', cwd=target)
        commit = git('rev-parse', 'HEAD', cwd=target).stdout.decode().strip()
        # A normal push retains history and rejects a concurrent update; never force-push.
        git('push', 'origin', 'HEAD:refs/heads/gh-pages', cwd=target)
        pushed = git('ls-remote', '--heads', 'origin', 'refs/heads/gh-pages', cwd=target).stdout.decode().split()[0]
        if pushed != commit:
            raise RuntimeError('Remote verification did not match the publication commit.')
        print(json.dumps({**details, 'publication_commit': commit, 'static_files': count}, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dry-run', action='store_true', help='inspect committed inputs without publishing')
    args = parser.parse_args()
    try:
        publish(args.dry_run)
    except (RuntimeError, subprocess.CalledProcessError) as error:
        if isinstance(error, subprocess.CalledProcessError):
            print(error.stderr.decode(errors='replace').strip())
        raise SystemExit(str(error))
